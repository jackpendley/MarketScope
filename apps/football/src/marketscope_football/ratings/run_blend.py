"""Research study R6: the frozen ratings-v1 blended with the closing market, walk-forward on 2023–24
(research/PREREGISTRATION.md, addendum A). Writes research/reports/r6-model-market-blend.md.

    PYTHONPATH=src .venv/bin/python -m marketscope_football.ratings.run_blend
"""

from __future__ import annotations

import subprocess
from datetime import datetime, timezone
from pathlib import Path

import pandas as pd

from ..eval.run_benchmarks import prepare
from ..eval.walkforward import run_models
from . import blend
from .live import build_model
from .version import FROZEN_PARAMS_SHA256, MODEL_VERSION, params_sha256

REPORT = Path(__file__).resolve().parents[5] / "research" / "reports" / "r6-model-market-blend.md"
WARM_UP, SCORED = (2022,), (2023, 2024)


def f(est: tuple[float, float, float] | None, dg: int = 4) -> str:
    return "–" if est is None else f"{est[0]:+.{dg}f} ({est[1]:+.{dg}f} to {est[2]:+.{dg}f})"


def main() -> None:
    if params_sha256() != FROZEN_PARAMS_SHA256:
        raise SystemExit("params.json differs from the frozen ratings-v1 parameters")
    games, sigma, _ = prepare()
    preds = run_models(games, {MODEL_VERSION: lambda: build_model(games, sigma)[0]}, [*WARM_UP, *SCORED])
    close = games.set_index("game_id")["close_p_home"]
    df = pd.DataFrame({"season": preds["season"], "week": preds["week"], "game_id": preds["game_id"],
                       "p_model": preds["p_home"], "p_close": preds["game_id"].map(close), "y": preds["home_win"]})
    missing = int(df[df["season"].isin(SCORED)]["p_close"].isna().sum())
    r = blend.r6(df, set(SCORED))
    code = subprocess.run(["git", "rev-parse", "--short", "HEAD"], capture_output=True, text=True).stdout.strip()
    ran = datetime.now(timezone.utc).date().isoformat()
    lo, hi = r["primary"][1], r["primary"][2]
    verdict = ("**The blend beats the close** (interval below 0)." if r["claim"] else
               "**Not distinguishable from the close**: no claim." if lo < 0 < hi else
               "**The blend is worse than the close** (interval above 0).")
    w = r["w_by_slot"]
    L = [f"# R6: {MODEL_VERSION} + market blend, 2023–24", "",
         f"_Generated by `marketscope_football.ratings.run_blend` on {ran} (code {code}, params sha256 "
         f"{FROZEN_PARAMS_SHA256[:12]}). Rules: research/PREREGISTRATION.md, R6 and addendum A, committed before this "
         "code. Research only: the displayed MarketScope rating never uses market inputs._", "",
         f"Blend p = w · p_model + (1 − w) · p_close. Each week's w is the weight that minimised the blend's Brier over "
         f"the previous {blend.TRAILING_SLOTS} week slots, capped at {blend.MAX_MODEL_WEIGHT} (market weight at least "
         f"{1 - blend.MAX_MODEL_WEIGHT:.2f}). p_close is the no-vig nflverse closing moneyline. Walk-forward predictions "
         f"of the frozen model; 2022 only fills the first trailing window.", "",
         f"## Primary: Brier(blend) − Brier(close), {r['games']} games", "",
         f"{f(r['primary'])}. {verdict}", "",
         "| Forecast | Brier | Log loss | Δ Brier vs close | Δ log loss vs close |", "|---|---|---|---|---|",
         *[f"| {k} | {v['brier']:.4f} | {v['log_loss']:.4f} | {f(v['d_brier'])} | {f(v['d_log_loss'])} |"
           for k, v in r["rows"].items()], "",
         "Δ = forecast minus close, game bootstrap (5,000 resamples); negative is better. Rows other than the "
         "trailing-w blend are exploratory.", "",
         "## The weight path (exploratory)", "",
         f"Mean model weight {r['w_mean']:.2f} over {r['slots']} week slots; {r['w_zero']} slots at 0 (pure market), "
         f"{r['w_at_cap']} at the {blend.MAX_MODEL_WEIGHT} cap.", "",
         "| Season | Weeks | Mean w | Min | Max |", "|---|---|---|---|---|",
         *[f"| {s} | {len(g)} | {g.mean():.2f} | {g.min():.2f} | {g.max():.2f} |" for s, g in w.groupby(level=0)], "",
         f"Scored games without a closing moneyline (excluded): {missing}.", ""]
    REPORT.write_text("\n".join(L))
    print("\n".join(L[6:12]))


if __name__ == "__main__":
    main()
