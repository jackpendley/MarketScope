"""KenPom-contract report (MS-030b): luck fits, checks, classic-KenPom agreement, the current
ratings table, Five Factors and model estimates for the next games. Writes reports/ratings-contract.md.

    PYTHONPATH=src .venv/bin/python -m marketscope_football.ratings.report_contract --out reports/ratings-contract.md
"""

from __future__ import annotations

import argparse
import json
from datetime import date
from pathlib import Path

import numpy as np
import pandas as pd
from scipy.stats import spearmanr

from ..eval.metrics import win_probability
from ..eval.run_benchmarks import prepare
from .design import BURN_IN_FROM, LIKELIHOOD_SEASONS
from .engine import PARAMS_PATH, Engine, load_params
from .fit import load_inputs
from .kenpom_classic import classic_ratings, season_team_games
from .luck import game_net_epa
from .outputs import MODEL_VERSION, home_advantage_points, snapshots


def fmt_rank(v, r, digits=2, sign=False):
    return "–" if pd.isna(v) else f"{v:+.{digits}f} ({int(r)})" if sign else f"{v:.{digits}f} ({int(r)})"


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", type=Path, default=Path("reports/ratings-contract.md"))
    args = ap.parse_args()
    games, sigma, _ = prepare()
    _, obs, teams, sf, wf = load_inputs("model")
    units, st, layer = load_params("model")
    params = json.loads(PARAMS_PATH.read_text())
    luck = params["luck"]
    eng = Engine(teams, units, st, obs, sf, wf)
    snap = snapshots(games, obs, eng, layer, luck, min(LIKELIHOOD_SEASONS), BURN_IN_FROM)
    hfa = home_advantage_points(eng, layer)

    # Home term in the expected-wins model.
    g = games.assign(net=game_net_epa(games, obs))
    g = g[g["season"].isin(LIKELIHOOD_SEASONS) & g["net"].notna()]
    slope, intercept = np.polyfit(g["net"], g["margin"], 1)
    neutral_mean = g.loc[g["neutral"], "margin"].mean()

    # Classic KenPom vs Kalman, end of regular season and early/mid season.
    rows = []
    for season in sorted(set(snap["season"])):
        s = snap[snap["season"] == season]
        reg_last = games[(games["season"] == season) & (games["game_type"] == "REG") & games["margin"].notna()]["week"].max()
        row = {"season": season}
        for label, wk in (("week 4", 4), ("week 9", 9), ("end of regular season", reg_last)):
            if wk > s["week"].max():
                row[label] = np.nan
                continue
            k = s[s["week"] == wk].set_index("team")["adj_em"]
            c = classic_ratings(season_team_games(games, obs, season, wk)).set_index("team")["adj_em"]
            row[label] = spearmanr(k, c.reindex(k.index))[0]
        rows.append(row)
    corr = pd.DataFrame(rows)

    latest_season = int(snap["season"].max())
    latest_week = int(snap.loc[snap["season"] == latest_season, "week"].max())
    cur = snap[(snap["season"] == latest_season) & (snap["week"] == latest_week)].sort_values("adj_em", ascending=False)
    luck_sum = snap.groupby(["season", "week"])["luck"].sum().abs().max()

    # Model estimates for the next unplayed games (same engine state as the latest snapshot).
    nxt = games[(games["season"] == latest_season) & games["margin"].isna()]
    nxt = nxt[nxt["week"] == nxt["week"].min()] if len(nxt) else nxt
    est = []
    for x in nxt.itertuples(index=False):
        f = eng.features(x.home, x.away, bool(x.neutral), layer)
        m = layer.margin(f, bool(x.neutral))
        t = layer.total(eng.raw_total(x.home, x.away, bool(x.neutral)))
        est.append((x.away, x.home, (t - m) / 2, (t + m) / 2, float(win_probability(np.array([m]), sigma)[0]), t, m))

    last_full = latest_season - 1
    reg_week = int(games[(games["season"] == last_full) & (games["game_type"] == "REG")]["week"].max())
    lf = snap[(snap["season"] == last_full) & (snap["week"] == reg_week)].sort_values("adj_em", ascending=False)

    ew, py = luck["expected_wins"], luck["pythag"]
    L = [
        "# MarketScope Ratings: the KenPom contract (MS-030b)", "",
        f"_Generated by `marketscope_football.ratings.report_contract` on {date.today().isoformat()} "
        f"(model `{MODEL_VERSION}`, parameters in `ratings/params.json`, fitted on 2016–22). Ratings are model "
        "estimates with the uncertainty shown; nothing here is a pick._", "",
        "## Definitions", "",
        "| Column | Meaning |", "|---|---|",
        f"| AdjEM | Expected margin vs an average team on a neutral field (points per game) = (AdjO − AdjD) × {layer.n_drives:.1f} drives + AdjST |",
        "| AdjO / AdjD | Points per drive scored / allowed vs an average opponent, built from the opponent-adjusted channel ratings (EPA, success rate, points per drive). Lower AdjD is better |",
        "| AdjST | Special-teams points per game vs average |",
        "| AdjPace | Drives per team-game vs an average opponent (KenPom's tempo; rank 1 = fastest) |",
        "| Luck | Wins − expected wins. Expected wins = Σ P(win \\| that game's net adjusted EPA and venue) |",
        "| SOS | Venue-adjusted average current AdjEM of opponents played (an opponent at home counts its home advantage) |",
        "| Prior weight | ≈ share of the rating still carried by the preseason prior (variance now ÷ variance at week 0) |", "",
        "## Luck model (fitted on 2016–22)", "",
        f"- Expected wins: logit P(win) = {ew['alpha']:.3f} × home + {ew['beta']:.3f} × net adjusted EPA ({ew['games']:,} games). "
        f"One extra point of net EPA is worth about {ew['beta'] / 4 * 100:.1f} percentage points of win probability near 50%.",
        f"- Pythagorean exponent: {py['exponent']:.2f} ({py['team_seasons']} team-seasons). The classic NFL value is 2.37; "
        "higher-scoring modern seasons push it up.",
        f"- **Home teams win more than their efficiency implies.** Margin ≈ {slope:.2f} × net adjusted EPA "
        f"{intercept:+.2f} points (2016–22). The {intercept:.1f}-point home term is outside scrimmage EPA "
        "(it is consistent with penalties, whose plays the channel excludes, and other non-scrimmage effects), "
        "so expected wins keep a home term instead of calling it luck.",
        f"- Check: league-wide luck sums to zero in every snapshot (max |sum| {luck_sum:.1e}).", "",
        "## Classic KenPom vs the Kalman engine (Spearman rank correlation of AdjEM)", "",
        "Classic KenPom iterates raw points per drive against opponents within a season (no prior, equal weights). "
        "Agreement rises as the season accumulates games; early on the Kalman engine leans on its prior.", "",
        "| Season | week 4 | week 9 | end of regular season |", "|---|---|---|---|",
        *[f"| {int(r['season'])} | " + " | ".join("–" if pd.isna(r[c]) else f"{r[c]:.2f}"
                                                for c in ("week 4", "week 9", "end of regular season")) + " |"
          for _, r in corr.iterrows()], "",
        f"## Current ratings: {latest_season} through week {latest_week}", "",
        f"Home advantage in the model: {hfa:.2f} points.", "",
        "| Rk | Team | W-L | AdjEM | AdjO | AdjD | AdjST | AdjPace | Luck | SOS | Prior weight |",
        "|---|---|---|---|---|---|---|---|---|---|---|",
    ]
    for _, r in cur.iterrows():
        rec = f"{r['wins']}-{r['losses']}" + (f"-{r['ties']}" if r["ties"] else "")
        L.append(f"| {int(r['adj_em_rank'])} | {r['team']} | {rec} | {r['adj_em']:+.1f} ± {r['adj_em_se']:.1f} | "
                 f"{fmt_rank(r['adj_o'], r['adj_o_rank'])} | {fmt_rank(r['adj_d'], r['adj_d_rank'])} | "
                 f"{fmt_rank(r['adj_st'], r['adj_st_rank'], sign=True)} | {fmt_rank(r['adj_pace'], r['adj_pace_rank'], 1)} | "
                 f"{fmt_rank(r['luck'], r['luck_rank'], sign=True)} | {fmt_rank(r['sos'], r['sos_rank'], sign=True)} | "
                 f"{r['prior_weight']:.0%} |")
    L += ["", "### Luck decomposition (same snapshot)", "",
          "| Team | W | Expected W | Pythag W | Luck | One-score games | Fumble luck (EPA) | INT luck (EPA) | FG luck (pts) | Return/def TD diff |",
          "|---|---|---|---|---|---|---|---|---|---|"]
    for _, r in cur.sort_values("luck", ascending=False).iterrows():
        L.append(f"| {r['team']} | {r['wins'] + 0.5 * r['ties']:g} | {r['expected_wins']:.1f} | {r['pythag_wins']:.1f} | "
                 f"{r['luck']:+.1f} | {r['one_score_luck']:+.1f} | {r['fumble_luck']:+.1f} | {r['int_luck']:+.1f} | "
                 f"{r['fg_luck']:+.1f} | {r['return_td_diff']:+d} |")
    L += ["", "### Five Factors (season to date, raw; ranks in brackets)", "",
          "| Team | Success off / def | Explosiveness off / def | Start yard line off / def | Pts per trip inside 40 off / def | Turnovers/game off / def |",
          "|---|---|---|---|---|---|"]
    ff = cur.copy()
    for c, asc in (("off_success_rate", False), ("def_success_rate", True), ("off_explosiveness", False),
                   ("def_explosiveness", True), ("off_start_yardline", False), ("def_start_yardline", True),
                   ("off_points_per_opp", False), ("def_points_per_opp", True), ("off_turnovers", True),
                   ("def_turnovers", False)):
        ff[f"{c}_r"] = ff[c].rank(ascending=asc, method="min")
    for _, r in ff.iterrows():
        cells = []
        for a, b, dg in (("off_success_rate", "def_success_rate", 3), ("off_explosiveness", "def_explosiveness", 2),
                         ("off_start_yardline", "def_start_yardline", 1), ("off_points_per_opp", "def_points_per_opp", 2),
                         ("off_turnovers", "def_turnovers", 2)):
            cells.append(f"{r[a]:.{dg}f} ({int(r[a + '_r'])}) / {r[b]:.{dg}f} ({int(r[b + '_r'])})")
        L.append(f"| {r['team']} | " + " | ".join(cells) + " |")
    if est:
        L += ["", f"## Model estimates for the next games ({latest_season} week {int(nxt['week'].min())})", "",
              "Predicted score for each team (they sum to the model total and differ by the model margin). "
              "Model estimate only; on 2023–24 its margin missed by 10.3 points on average (the market close: 9.8).", "",
              "| Away | Home | Model score | Home win prob | Total |", "|---|---|---|---|---|"]
        for a, h, sa, sh, p, t, m in est:
            assert abs((sa + sh) - t) < 1e-9 and abs((sh - sa) - m) < 1e-9
            L.append(f"| {a} | {h} | {sa:.1f}–{sh:.1f} | {p:.0%} | {t:.1f} |")
    L += ["", f"## {last_full} at the end of the regular season (week {reg_week})", "",
          "| Rk | Team | W-L | AdjEM | AdjO | AdjD | Luck |", "|---|---|---|---|---|---|---|"]
    for _, r in pd.concat([lf.head(10), lf.tail(5)]).iterrows():
        L.append(f"| {int(r['adj_em_rank'])} | {r['team']} | {r['wins']}-{r['losses']} | {r['adj_em']:+.1f} | "
                 f"{r['adj_o']:.2f} | {r['adj_d']:.2f} | {r['luck']:+.1f} |")
    L.append("")
    args.out.write_text("\n".join(L))
    print(f"wrote {args.out}")
    print(corr.round(2).to_string(index=False))


if __name__ == "__main__":
    main()
