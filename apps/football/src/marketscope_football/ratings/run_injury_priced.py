"""Research study R2h: are final-report absences priced in the close? Walk-forward 2016–24 with the
frozen ratings-v1 (research/PREREGISTRATION.md, addendum B). Writes research/reports/r2h-injuries-priced.md.

    PYTHONPATH=src .venv/bin/python -m marketscope_football.ratings.run_injury_priced
"""

from __future__ import annotations

import subprocess
from datetime import datetime, timezone
from pathlib import Path

import pandas as pd

from ..eval.run_benchmarks import prepare
from ..eval.walkforward import walk_forward
from . import injury_priced as ip
from .live import build_model
from .version import FROZEN_PARAMS_SHA256, MODEL_VERSION, params_sha256

REPORT = Path(__file__).resolve().parents[5] / "research" / "reports" / "r2h-injuries-priced.md"
SEASONS = range(2016, 2025)


def f(e: tuple[float, float, float], dg: int = 3) -> str:
    return f"{e[0]:+.{dg}f} ({e[1]:+.{dg}f} to {e[2]:+.{dg}f})"


def main() -> None:
    if params_sha256() != FROZEN_PARAMS_SHA256:
        raise SystemExit("params.json differs from the frozen ratings-v1 parameters")
    games, sigma, _ = prepare()
    rec = ip.RecordingModel(build_model(games, sigma)[0])
    preds = walk_forward(games, rec, SEASONS)
    g = games.set_index("game_id")
    df = preds.merge(pd.DataFrame(rec.rows).drop_duplicates("game_id"), on="game_id")
    df = df[df["game_id"].map(g["game_type"]) == "REG"]
    df["ats"] = df["actual_margin"] - df["game_id"].map(g["close_margin"])
    r = ip.r2h(df)
    code = subprocess.run(["git", "rev-parse", "--short", "HEAD"], capture_output=True, text=True).stdout.strip()
    ran = datetime.now(timezone.utc).date().isoformat()
    verdict = {"under-priced": "**Absences are under-priced** (interval above 0).",
               "over-priced": "**Absences are over-priced** (interval below 0)."}.get(
        r["claim"], "**Not distinguishable from zero**: no claim.")
    if not r["gate"]:
        verdict = "Inconclusive (gate not met)."
    L = [f"# R2h: are final-report absences priced in the close? 2016–24", "",
         f"_Generated by `marketscope_football.ratings.run_injury_priced` on {ran} (code {code}, params sha256 "
         f"{FROZEN_PARAMS_SHA256[:12]}). Rules: research/PREREGISTRATION.md, addendum B, committed before this code._", "",
         f"A is the injury part of each {MODEL_VERSION} estimate: the QB term plus the non-QB availability terms of the "
         "game layer, in points toward the home team, computed from the final weekly injury report and reserve lists "
         "(published before kickoff, so the close had the same information). Walk-forward, regular seasons. A is "
         "non-zero in almost every game because the QB term compares each team's expected starter with its usual "
         "starter's value, healthy or not; the non-QB terms are zero unless a recent starter is listed or on a reserve list.", "",
         f"## Primary: ATS residual on A, {r['games']} games ({r['nonzero']} with A ≠ 0; gate {ip.MIN_GAMES})", "",
         f"Slope {f(r['primary'])} points of result vs the close per point of A. {verdict}", "",
         f"A has mean |A| {r['a_abs_mean']:.2f} and SD {r['a_sd']:.2f} points. A slope of 0 means the close already "
         "carries the model's injury adjustment; 1 would mean the close ignores it entirely.", "",
         "## Exploratory", "",
         "| Term | Slope (95% CI) |", "|---|---|",
         f"| QB part | {f(r['qb'])} |", f"| Non-QB part | {f(r['other'])} |", "",
         f"Games with |A| ≥ {ip.BIG}: {r['big_games']}; mean ATS residual in the direction of A "
         f"{f(r['big_directed'], 2)} points.", "",
         "Slope by season: " + ", ".join(f"{s} {v:+.2f}" for s, v in r["per_season"].items()) + ".", "",
         "Game bootstrap, 5,000 resamples (seed 2026). Research only.", ""]
    REPORT.write_text("\n".join(L))
    print("\n".join(L[6:10]))


if __name__ == "__main__":
    main()
