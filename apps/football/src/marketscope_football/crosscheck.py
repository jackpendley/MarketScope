"""Cross-check our play-by-play aggregates against nflverse's own team stats (load_team_stats),
which are built independently from the same plays. Counts should agree exactly; EPA differs by
definition (nflverse sums player-credited EPA and excludes penalty-nullified plays), so it is
compared by correlation and mean absolute difference.

    PYTHONPATH=src .venv/bin/python -m marketscope_football.crosscheck --seasons 2016-2026 --out reports/team-stats-crosscheck.md
"""

from __future__ import annotations

import argparse
from pathlib import Path

import nflreadpy as nfl
import numpy as np
import polars as pl

from .pbp import load_season
from .team_stats import team_game_stats

# ours -> nflverse team-stats column (same team, same game)
COUNT_PAIRS = [
    ("sacks", "sacks_suffered"),
    ("interceptions", "passing_interceptions"),
    ("fg_attempts", "fg_att"),
    ("fg_made", "fg_made"),
    ("xp_attempts", "pat_att"),
    ("xp_made", "pat_made"),
    ("penalties", "penalties"),
    ("penalty_yards", "penalty_yards"),
]


def aligned_epa(pbp: pl.DataFrame) -> pl.DataFrame:
    """EPA under nflverse's team-stats definition: passes and runs that counted (no
    penalty-nullified plays), passes credited with `qb_epa` (the passer's EPA up to a fumble)."""
    plays = pbp.filter(pl.col("play_type").is_in(["pass", "run"]) & pl.col("epa").is_not_null())
    value = pl.when(pl.col("pass") == 1).then(pl.col("qb_epa")).otherwise(pl.col("epa"))
    return plays.group_by("game_id", pl.col("posteam").alias("team")).agg(aligned_epa=value.sum())


def compare(ours: pl.DataFrame, theirs: pl.DataFrame) -> tuple[list[dict], dict, int]:
    theirs = theirs.with_columns(
        their_epa=pl.col("passing_epa").fill_null(0) + pl.col("rushing_epa").fill_null(0),
        their_plays=pl.col("attempts") + pl.col("sacks_suffered") + pl.col("carries"),
    )
    j = ours.join(theirs, on=["game_id", "team"], how="inner", suffix="_nflverse")
    rows = []
    for a, b in COUNT_PAIRS:
        right = f"{b}_nflverse" if b in ours.columns else b
        diff = (j[a] - j[right].fill_null(0)).abs()
        rows.append({"ours": a, "nflverse": b, "exact": float((diff == 0).mean()), "max_abs_diff": int(diff.max())})
    our_epa = (j["epa_per_play"] * j["plays"]).to_numpy()
    their_epa = j["their_epa"].to_numpy()
    epa = {
        "corr_total": float(np.corrcoef(our_epa, their_epa)[0, 1]),
        "mean_abs_diff_total": float(np.mean(np.abs(our_epa - their_epa))),
        "corr_aligned": float(np.corrcoef(j["aligned_epa"].to_numpy(), their_epa)[0, 1]),
        "mean_abs_diff_aligned": float(np.mean(np.abs(j["aligned_epa"].to_numpy() - their_epa))),
    }
    return rows, epa, j.height


def main() -> None:
    from .ingest import parse_seasons

    ap = argparse.ArgumentParser()
    ap.add_argument("--seasons", default="2016-2026")
    ap.add_argument("--out")
    args = ap.parse_args()
    seasons = parse_seasons(args.seasons)
    lines = [
        "# Team-game stats vs nflverse team stats",
        "",
        "Generated by `python -m marketscope_football.crosscheck`. Our `nfl_team_game_stats` aggregates "
        "(from play-by-play) compared with nflverse `load_team_stats(summary_level='week')`, team by game.",
        "",
        "| Season | Team-games | " + " | ".join(a for a, _ in COUNT_PAIRS) + " | EPA corr | EPA mean abs diff | EPA corr, aligned | aligned mean abs diff |",
        "| --- | --- | " + " | ".join("---" for _ in COUNT_PAIRS) + " | --- | --- | --- | --- |",
    ]
    for s in seasons:
        pbp = load_season(s)
        ours = team_game_stats(pbp).join(aligned_epa(pbp), on=["game_id", "team"], how="left")
        theirs = nfl.load_team_stats([s], summary_level="week")
        rows, epa, n = compare(ours, theirs)
        cells = " | ".join(f"{r['exact']:.1%}" + (f" (max {r['max_abs_diff']})" if r["exact"] < 1 else "") for r in rows)
        lines.append(f"| {s} | {n} | {cells} | {epa['corr_total']:.3f} | {epa['mean_abs_diff_total']:.2f} | {epa['corr_aligned']:.4f} | {epa['mean_abs_diff_aligned']:.2f} |")
        print(lines[-1])
    lines += [
        "",
        "Cells are the share of team-games where the count matches exactly (with the largest difference "
        "when it does not). EPA is compared on game totals: ours sums `epa` over scrimmage plays including "
        "penalty-nullified passes and runs (the nflfastR convention for team efficiency); nflverse sums "
        "player-credited passing and rushing EPA. The *aligned* columns recompute ours under the nflverse "
        "definition (no nullified plays; passes credited with `qb_epa`), showing the gap is definitional.",
    ]
    if args.out:
        Path(args.out).parent.mkdir(parents=True, exist_ok=True)
        Path(args.out).write_text("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
