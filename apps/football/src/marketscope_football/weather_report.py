"""Report: how good are the stored point-in-time forecasts? Compares each lead's game-window
forecast with nflverse's observed game temperature and wind (outdoor venues only).

    DATABASE_URL=... PYTHONPATH=src .venv/bin/python -m marketscope_football.weather_report --out reports/weather-forecast-skill.md
"""

from __future__ import annotations

import argparse
from pathlib import Path

from .db import connect

QUERY = """
SELECT w.lead_days, count(*) AS n,
       corr(w.temperature_f, g.observed_temp_f) AS temp_r, avg(abs(w.temperature_f - g.observed_temp_f)) AS temp_mae,
       corr(w.wind_mph, g.observed_wind_mph) AS wind_r, avg(abs(w.wind_mph - g.observed_wind_mph)) AS wind_mae,
       avg((w.wind_mph >= 15)::int) AS windy_share
FROM nfl_weather_forecasts w
JOIN nfl_games g USING (game_id)
JOIN nfl_game_context c ON c.game_id = g.game_id AND c.team = g.away_team
WHERE c.roof_type = 'outdoor' AND g.observed_temp_f IS NOT NULL AND g.observed_wind_mph IS NOT NULL
GROUP BY w.lead_days ORDER BY w.lead_days
"""


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--out")
    args = ap.parse_args()
    with connect() as conn:
        rows = conn.execute(QUERY).fetchall()
        totals = conn.execute("SELECT count(DISTINCT game_id), min(forecast_hour_utc)::date, max(forecast_hour_utc)::date "
                              "FROM nfl_weather_forecasts").fetchone()
    lines = [
        "# Weather forecast skill (point-in-time)",
        "",
        "Generated by `python -m marketscope_football.weather_report`. Forecasts: Open-Meteo Previous Runs API "
        "(CC-BY 4.0), averaged over the game window (kickoff hour + 3); lead N days = predicted at least N x 24 h "
        "before the hour. Observed: nflverse game-time temperature and wind (post-hoc). Outdoor venues only "
        f"(retractable roofs excluded because the roof state is unknown). {totals[0]} games with forecasts, "
        f"{totals[1]} to {totals[2]}.",
        "",
        "| Lead (days) | Games | Temperature r | Temperature MAE (°F) | Wind r | Wind MAE (mph) | Forecast wind ≥ 15 mph |",
        "| --- | --- | --- | --- | --- | --- | --- |",
    ]
    for lead, n, tr, tm, wr, wm, windy in rows:
        lines.append(f"| {lead} | {n} | {tr:.3f} | {tm:.1f} | {wr:.3f} | {wm:.1f} | {windy:.1%} |")
    lines += [
        "",
        "Temperature is forecast well a week out. Wind skill holds at 1 to 3 days and largely disappears by 7 "
        "days, so wind enters the totals model from short-lead forecasts only. The R3 study (does a wind "
        "forecast crossing 15 mph move the totals market, and when?) uses the 1 and 3-day leads.",
        "",
        "Caveat: nflverse's observed wind is a single game-time reading, so part of the wind error is "
        "measurement noise, not forecast error.",
    ]
    print("\n".join(lines))
    if args.out:
        Path(args.out).write_text("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
