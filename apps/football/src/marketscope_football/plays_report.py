"""Report: how often do players listed on the final injury report actually play?

Estimated on the 2016-2022 fitting seasons, with 2023-2025 shown as an out-of-sample check
(docs/RATINGS.md validation protocol). "Played" = at least one offensive, defensive or
special-teams snap (PFR snap counts via nflverse).

    PYTHONPATH=src .venv/bin/python -m marketscope_football.plays_report --out reports/plays-given-status.md
"""

from __future__ import annotations

import argparse
from pathlib import Path

import nflreadpy as nfl
import polars as pl

from .availability import GROUP_ORDER, STATUSES, rate_table, snap_rows, status_outcomes
from .design import FIT_SEASONS

CHECK_SEASONS = (2023, 2024, 2025)


def _fmt(row: dict) -> str:
    return f"{row['p']:.1%} ({row['lo']:.1%}–{row['hi']:.1%}), n = {row['n']:,}"


def build(fit: pl.DataFrame, check: pl.DataFrame) -> list[str]:
    lines = [
        "# P(plays | injury-report status)",
        "",
        "Generated by `python -m marketscope_football.plays_report` from nflverse injury reports and PFR snap "
        "counts. **Played** = at least one snap of any kind. Fit seasons 2016–2022; 2023–2025 is an "
        "out-of-sample check. Brackets are 95% Wilson intervals.",
        "",
        "## By game status",
        "",
        "| Status | 2016–22 | 2023–25 | ELWAY assumption |",
        "| --- | --- | --- | --- |",
    ]
    elway = {"Questionable": "≈ 70% (QB)", "Doubtful": "≈ 7% (QB)", "Out": "0%"}
    f, c = rate_table(fit, ["report_status"]), rate_table(check, ["report_status"])
    for s in STATUSES:
        fr, cr = f.filter(pl.col("report_status") == s).to_dicts(), c.filter(pl.col("report_status") == s).to_dicts()
        lines.append(f"| {s} | {_fmt(fr[0]) if fr else '—'} | {_fmt(cr[0]) if cr else '—'} | {elway[s]} |")

    lines += ["", "## Questionable, by final practice status of the week", "",
              "| Last practice | 2016–22 | 2023–25 |", "| --- | --- | --- |"]
    q = pl.col("report_status") == "Questionable"
    f, c = rate_table(fit.filter(q), ["practice"]), rate_table(check.filter(q), ["practice"])
    for level in ("Full", "Limited", "DNP"):
        fr, cr = f.filter(pl.col("practice") == level).to_dicts(), c.filter(pl.col("practice") == level).to_dicts()
        lines.append(f"| {level} | {_fmt(fr[0]) if fr else '—'} | {_fmt(cr[0]) if cr else '—'} |")

    lines += ["", "## Questionable, by position group (2016–22)", "",
              "| Group | P(plays) |", "| --- | --- |"]
    g = rate_table(fit.filter(q), ["group"])
    for grp in GROUP_ORDER:
        r = g.filter(pl.col("group") == grp).to_dicts()
        if r:
            lines.append(f"| {grp} | {_fmt(r[0])} |")
    lines += [
        "",
        "## Reading this",
        "",
        "- **Out means out**, and **Doubtful almost always does too**: under 1% of Doubtful players play in "
        "either era, far below the ≈ 7% that ELWAY assumes for quarterbacks (our QB sample: 0 of 39).",
        "- **Questionable is stable overall** (≈ 68% then, ≈ 66% now) **but the practice signal has weakened.** "
        "In 2016–22 a full Friday practice meant 85% and a missed one 41%; in 2023–25 those are 71% and 52%. "
        "A model fit only on 2016–22 would be overconfident about practice status today.",
        "- Consequence for MS-031: P(plays) is modelled from status × practice with the practice effect allowed "
        "to drift (estimated on a rolling window of seasons before the prediction), shrunk across position "
        "groups, and checked on 2023–24 validation. Never tuned on the 2025 test season.",
        "- Quarterbacks listed Questionable play less often (53%) than other positions, but the sample is small "
        "(n = 219) and the interval wide.",
        "- Limitation: \"played\" is any snap. A Questionable player who plays may still play less than "
        "usual; snap-share effects are modelled in MS-031.",
    ]
    return lines


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--out")
    args = ap.parse_args()
    seasons = [*FIT_SEASONS, *CHECK_SEASONS]
    players = nfl.load_players()
    snaps = snap_rows(nfl.load_snap_counts(seasons), players)
    outcomes = status_outcomes(nfl.load_injuries(seasons), snaps)
    fit = outcomes.filter(pl.col("season").is_in(list(FIT_SEASONS)))
    check = outcomes.filter(pl.col("season").is_in(list(CHECK_SEASONS)))
    lines = build(fit, check)
    print("\n".join(lines))
    if args.out:
        Path(args.out).write_text("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
